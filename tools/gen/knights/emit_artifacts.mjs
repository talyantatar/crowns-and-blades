// emit_artifacts.mjs - CK3 script that logs the equipped artifacts of battle characters (proposal for the CK3 mod).
//
// The mod adopts the CX part only: tools/gen/gen_ck3_mod.mjs renders cxArtifactEffectLines() into
// common/scripted_effects/ck3xbl_gen_knight_effects.txt and calls ck3xbl_emit_cx_artifacts_effect from ck3xbl_emit_cx_effect
// (every C record, this = character). The AX|ke_art part (ck3xbl_emit_ax_knight_artifacts_effect, in army_owner = { ... } of the
// A record) is not adopted: artifact knight effectiveness is inside ck3xbl_a_ke.
// ck3ArtifactEffects() prints both parts for this tool's --write / --lint.
// Records (all without a dump; PROTOCOL §5 grammar):
//   CX|artifact|<slot_type>|<type>|<rarity>    one per equipped artifact in slot type primary_armament/armor/helmet;
//                                               <type> = unknown for a type this table does not know (modded)
//   CX|artifact_helmet|<armor_helmet_feature>  after an armour line: the armour's helmet shape (armor_helmet group)
//   AX|ke_art|<modifier key>                   army owner: one per equipped artifact modifier with knight effectiveness
//                                               (only when the owner can benefit from that artifact)
// The bridge looks the values up in bridge/data/ck3_artifact_types.json and ck3_artifact_to_bl_items.json.
//
// Usage: node tools/gen/knights/emit_artifacts.mjs [--write <file>] [--lint]
//   prints (or writes) the script for the current tables; --lint runs tools/gen/lint_ck3_mod.mjs lintMod() on the mod
//   with this file added and the two calls inserted IN MEMORY (nothing in ck3_mod/ is touched).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..', '..', '..');
const BATTLE_SLOTS = ['primary_armament', 'armor', 'helmet'];
const RARITIES = ['common', 'masterwork', 'famed', 'illustrious'];

export const ARTIFACT_EFFECTS_FILE = 'common/scripted_effects/ck3xbl_gen_artifact_effects.txt';

const readArtifactTypes = () => JSON.parse(fs.readFileSync(path.join(REPO, 'bridge', 'data', 'ck3_artifact_types.json'), 'utf8'));

/** Script text (without BOM) for the current ck3_artifact_types.json. */
export function ck3ArtifactEffects(types = readArtifactTypes()) {
  const keMods = types.knight_effectiveness_modifiers.map((m) => m.key);
  const L = [];
  L.push('# GENERATED by tools/gen/knights/emit_artifacts.mjs from bridge/data/ck3_artifact_types.json - do not edit by hand.');
  L.push('# Equipped artifacts of battle characters (PROTOCOL.md §13.2).');
  L.push('');
  L.push('# this = character (a C|CMD or C|KNIGHT record was just written). One CX|artifact line per equipped artifact in');
  L.push(`# slot type ${BATTLE_SLOTS.join(' / ')}; armour adds its helmet shape (CX|artifact_helmet).`);
  L.push(...cxArtifactEffectLines(types));
  L.push('');
  L.push('# this = character (the owner of an army in the snapshot). One AX|ke_art line per equipped artifact modifier that');
  L.push('# carries knight_effectiveness_mult, only when the owner benefits from that artifact (template can_benefit).');
  L.push('# Court-slot artifacts (wall banners, thrones, ...) are equipped too and are included.');
  L.push('ck3xbl_emit_ax_knight_artifacts_effect = {');
  L.push('\tevery_equipped_character_artifact = {');
  L.push('\t\tsave_temporary_scope_as = ck3xbl_art');
  L.push('\t\tif = {');
  L.push('\t\t\tlimit = { artifact_owner = { can_benefit_from_artifact = scope:ck3xbl_art } }');
  for (const m of keMods) L.push(`\t\t\tif = { limit = { has_artifact_modifier = ${m} } info_log = "CK3XBL|AX|ke_art|${m}" }`);
  L.push('\t\t}');
  L.push('\t}');
  L.push('}');
  return `${L.join('\n')}\n`;
}

/**
 * Lines of `ck3xbl_emit_cx_artifacts_effect = { ... }` (tab-indented from depth 0): the CX|artifact / CX|artifact_helmet part,
 * which the mod generator (tools/gen/gen_ck3_mod.mjs) adopts; this = the character of a C record.
 */
export function cxArtifactEffectLines(types = readArtifactTypes()) {
  const battleTypes = types.types.filter((t) => t.bl_category && BATTLE_SLOTS.includes(t.slot_type));
  const helmetFeatures = types.feature_groups.armor_helmet || [];
  const L = [];
  L.push('ck3xbl_emit_cx_artifacts_effect = {');
  L.push('\tevery_equipped_character_artifact = {');
  L.push(`\t\tlimit = { OR = { ${BATTLE_SLOTS.map((s) => `artifact_slot_type = ${s}`).join(' ')} } }`);
  for (const rarity of RARITIES) {
    L.push(`\t\t${rarity === RARITIES[0] ? 'if' : 'else_if'} = {`);
    L.push(`\t\t\tlimit = { rarity = ${rarity} }`);
    battleTypes.forEach((t, i) => {
      L.push(`\t\t\t${i === 0 ? 'if' : 'else_if'} = { limit = { artifact_type = ${t.key} } info_log = "CK3XBL|CX|artifact|${t.slot_type}|${t.key}|${rarity}" }`);
    });
    BATTLE_SLOTS.forEach((s) => {
      L.push(`\t\t\telse_if = { limit = { artifact_slot_type = ${s} } info_log = "CK3XBL|CX|artifact|${s}|unknown|${rarity}" }`);
    });
    L.push('\t\t}');
  }
  L.push('\t\tif = {');
  L.push('\t\t\tlimit = { artifact_slot_type = armor }');
  helmetFeatures.forEach((f, i) => {
    L.push(`\t\t\t${i === 0 ? 'if' : 'else_if'} = { limit = { has_artifact_feature = ${f} } info_log = "CK3XBL|CX|artifact_helmet|${f}" }`);
  });
  L.push('\t\t}');
  L.push('\t}');
  L.push('}');
  return L;
}

async function lintWithEffects(text) {
  const { lintMod } = await import('../lint_ck3_mod.mjs');
  const modDir = path.join(REPO, 'ck3_mod', 'ck3xbl');
  const sideFile = 'common/scripted_effects/ck3xbl_gen_side_effects.txt';
  let side = fs.readFileSync(path.join(modDir, ...sideFile.split('/')), 'utf8');
  if (side.charCodeAt(0) === 0xfeff) side = side.slice(1);
  const hooked = side
    .replaceAll('ck3xbl_emit_cx_effect = yes', 'ck3xbl_emit_cx_effect = yes\n\t\t\t\tck3xbl_emit_cx_artifacts_effect = yes')
    .replaceAll('army_owner = { ck3xbl_emit_ax_effect = yes }', 'army_owner = { ck3xbl_emit_ax_effect = yes ck3xbl_emit_ax_knight_artifacts_effect = yes }');
  const hooks = (hooked.match(/ck3xbl_emit_cx_artifacts_effect = yes/g) || []).length;
  const axHooks = (hooked.match(/ck3xbl_emit_ax_knight_artifacts_effect = yes/g) || []).length;
  const base = lintMod({ modDir });
  const res = lintMod({ modDir, overrides: { [ARTIFACT_EFFECTS_FILE]: text, [sideFile]: hooked } });
  const key = (p) => `${p.level}|${p.file}|${p.message}`;
  const before = new Set(base.problems.map(key));
  const added = res.problems.filter((p) => !before.has(key(p)));
  // The three new record shapes are not in the lint's RECORD grammar yet (tools/gen/lint_ck3_mod.mjs:194-200);
  // those errors are expected until the grammar gains GRAMMAR_ADDITIONS.
  const grammar = added.filter((p) => /does not match the record grammar/.test(p.message) && GRAMMAR_ADDITIONS.some((g) => new RegExp(`^${g}$`).test(p.message.match(/'([^']+)'/)[1].replace(/^CK3XBL\|/, ''))));
  const other = added.filter((p) => !grammar.includes(p));
  return { hooks, axHooks, baseProblems: base.problems.length, problems: res.problems.length, grammar, other, summary: res.summary };
}

/** Record shapes to add to the lint's RECORD alternatives (and to PROTOCOL §1.2/§5) when the effects are wired in. */
export const GRAMMAR_ADDITIONS = [
  'CX\\|artifact\\|[a-z_]+\\|[A-Za-z0-9_]+\\|[a-z]+',
  'CX\\|artifact_helmet\\|[A-Za-z0-9_]+',
  'AX\\|ke_art\\|[A-Za-z0-9_]+',
];

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = ck3ArtifactEffects();
  const wi = process.argv.indexOf('--write');
  if (wi > 0) {
    fs.mkdirSync(path.dirname(path.resolve(process.argv[wi + 1])), { recursive: true });
    fs.writeFileSync(path.resolve(process.argv[wi + 1]), `﻿${text}`, 'utf8');
  } else if (!process.argv.includes('--lint')) {
    process.stdout.write(text);
  }
  if (process.argv.includes('--lint')) {
    const r = await lintWithEffects(text);
    console.log(`hooks inserted in memory: ${r.hooks} x ck3xbl_emit_cx_artifacts_effect, ${r.axHooks} x ck3xbl_emit_ax_knight_artifacts_effect`);
    console.log(`lint problems: ${r.baseProblems} without -> ${r.problems} with the artifact effects`);
    console.log(`  expected (record grammar not extended yet, GRAMMAR_ADDITIONS): ${r.grammar.length}`);
    console.log(`  other new problems: ${r.other.length}`);
    for (const p of r.other) console.log(`  ${p.level} ${p.file}:${p.line} ${p.message}`);
    if (r.summary) console.log(typeof r.summary === 'string' ? r.summary : JSON.stringify(r.summary));
    process.exit(r.other.some((p) => p.level === 'error') ? 1 : 0);
  }
}
